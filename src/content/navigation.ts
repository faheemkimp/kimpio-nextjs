/**
 * Main navigation, based on the live kimp.io header (logged-out menu,
 * WordPress menu "logout-main-menu-new"). Link labels, descriptions, destinations
 * and image alt text are kept exactly as live so internal linking does not change.
 * Destinations keep their live form (decision D4 in SEO-URL-AUDIT.md), including
 * "/case-study" without a trailing slash.
 *
 * Every dropdown renders as a mega menu panel: grouped link rows with vector (lucide)
 * icons, plus a dark intro card with 3D art (or the case study card under "Our Work").
 * Icon names map to components in src/components/layout/nav-icon.tsx; intro art is
 * generated by scripts/generate-nav-icons.mjs into public/images/nav/.
 */

export type NavIcon =
  | "graphics"
  | "video"
  | "calculator"
  | "platform"
  | "updates"
  | "graphics-samples"
  | "video-samples"
  | "compare"
  | "testimonials"
  | "case-studies"
  | "about"
  | "contact"
  | "blog"
  | "book-call"
  | "affiliates"
  | "design-categories"
  | "brand-assets"
  | "media-kit"
  | "careers"
  | "login";

export interface NavLink {
  label: string;
  href: string;
  description?: string;
  icon?: NavIcon;
  image?: { src: string; alt: string };
}

export interface NavGroup {
  heading?: string;
  links: NavLink[];
}

export interface FeaturedCaseStudy {
  kind: "case-study";
  heading: string;
  intro: string;
  title: string;
  quote: string;
  cta: string;
  href: string;
  image: { src: string; alt: string };
}

export interface MegaIntro {
  title: string;
  text: string;
  /** Transparent 3D object shown in the corner of the dark intro card. */
  image: string;
  link?: { label: string; href: string };
}

export interface MegaItem {
  kind: "mega";
  label: string;
  intro: MegaIntro;
  /** "cards": icon + label + description. "images": photo tiles. "compact": icon + label rows in columns. */
  layout: "cards" | "images" | "compact";
  groups: NavGroup[];
  /** Rendered as a wide card inside the link grid. */
  featured?: FeaturedCaseStudy;
}

export type NavItem = { kind: "link"; label: string; href: string } | MegaItem;

